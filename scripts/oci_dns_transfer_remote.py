"""Stdlib helper sent over SSH to the Oracle Linux lab VMs; never prints keys."""
import base64
import hashlib
import json
import os
from pathlib import Path
import re
import secrets
import subprocess
import tempfile


def command(argv):
    return subprocess.run(argv, text=True, capture_output=True, timeout=20)


def checked(argv):
    result = command(argv)
    if result.returncode:
        raise RuntimeError('Command failed: ' + argv[0] + ': ' + result.stderr[-1000:])
    return result.stdout


def prepare_content(text, marker):
    # Deliberately support only the static one-line SOA/probe format generated by this lab.
    soa = re.search(r'^@\s+IN\s+SOA\s+\S+\s+\S+\s+\(\s*(\d+)', text, re.M)
    if not soa:
        raise ValueError('Expected the lab one-line SOA record')
    serial = (int(soa.group(1)) + 1) % (2 ** 32)
    text = text[:soa.start(1)] + str(serial) + text[soa.end(1):]
    text, count = re.subn(r'^probe\s+IN\s+TXT\s+"[^"\n]*"\s*$',
                          'probe IN TXT "' + marker + '"', text, flags=re.M)
    if count != 1:
        raise ValueError('Expected exactly one lab probe TXT record')
    return text.rstrip('\n') + '\n', serial


def transfer(item, key_file):
    # dig -k with a multi-key include may pick the wrong key. Extract just this zone's key.
    content = Path(key_file).read_text()
    pattern = r'key\s+"' + re.escape(item['keyName']) + r'"\s*\{[^{}]*\}\s*;'
    matches = re.findall(pattern, content)
    if len(matches) != 1:
        raise ValueError('Missing or duplicate per-zone key on VM-B: ' + item['zone'])
    with tempfile.TemporaryDirectory(prefix='oci-transfer-key-') as directory:
        key_path = Path(directory) / 'key.conf'
        key_path.write_text(matches[0])
        key_path.chmod(0o600)
        result = command(['dig', '-k', str(key_path), '@127.0.0.1', item['zone'],
                          'AXFR', '+noall', '+answer', '+time=3', '+tries=1'])
        if (result.returncode or 'Transfer failed' in result.stdout or
                re.search(r'verify.*signature|TSIG|BADSIG|BADKEY', result.stderr, re.I)):
            raise ValueError('Signed AXFR from VM-B failed: ' + item['zone'])
        unsigned = command(['dig', '@127.0.0.1', item['zone'], 'AXFR',
                            '+noall', '+answer', '+time=3', '+tries=1'])
        # Also try the right key name with a wrong secret, without printing it.
        wrong = re.sub(r'secret\s+"[^"]+"',
                       'secret "' + base64.b64encode(secrets.token_bytes(32)).decode() + '"',
                       matches[0])
        key_path.write_text(wrong)
        bad = command(['dig', '-k', str(key_path), '@127.0.0.1', item['zone'],
                       'AXFR', '+noall', '+answer', '+time=3', '+tries=1'])
        def rejected(reply):
            return bool(reply.returncode or 'Transfer failed' in reply.stdout or
                        not re.search(r'\sIN\s+SOA\s', reply.stdout))
        if not rejected(unsigned) or not rejected(bad):
            raise ValueError('Unsigned/wrong-secret AXFR unexpectedly succeeded: ' + item['zone'])
        return {'zone': item['zone'], 'axfr': result.stdout,
                'unsignedRejected': True, 'wrongSecretRejected': True}


def dispatch(request):
    operation = request['operation']
    if operation == 'cursor':
        text = checked(['journalctl', '-u', 'named', '-n', '1', '--show-cursor',
                        '--no-pager', '-o', 'json'])
        cursor = re.search(r'^-- cursor: (.+)$', text, re.M)
        if not cursor:
            raise ValueError('No named journal cursor; check service/logging configuration')
        return {'cursor': cursor.group(1)}
    if operation == 'logs':
        text = checked(['journalctl', '-u', 'named', '--after-cursor', request['cursor'],
                        '--no-pager', '-o', 'json'])
        return {'messages': [json.loads(line).get('MESSAGE', '') for line in text.splitlines()
                             if line.startswith('{')]}
    if operation == 'axfr':
        return {'transfers': [transfer(item, request['keyFile']) for item in request['zones']]}
    if operation == 'notify':
        for item in request['zones']:
            checked(['rndc', 'notify', item['zone']])
        return {'notified': len(request['zones'])}
    if operation == 'prepare':
        records = []
        for item in request['zones']:
            path = Path('/var/named') / (item['zone'] + '.zone')
            original = path.read_text()
            changed, serial = prepare_content(original, request['marker'])
            with tempfile.NamedTemporaryFile(mode='w', prefix='oci-zone-check-', delete=False) as stream:
                stream.write(changed)
                temp = stream.name
            try:
                checked(['named-checkzone', item['zone'], temp])
            finally:
                os.unlink(temp)
            records.append({'zone': item['zone'], 'serial': serial,
                            'beforeSha256': hashlib.sha256(original.encode()).hexdigest()})
        return {'prepared': records}
    if operation == 'publish':
        backup_tag = request.get('backupTag', request['marker'])
        if not re.fullmatch(r'[A-Za-z0-9_-]+', backup_tag):
            raise ValueError('Invalid backup tag')
        prepared = []
        for item in request['prepared']:
            path = Path('/var/named') / (item['zone'] + '.zone')
            original = path.read_text()
            if hashlib.sha256(original.encode()).hexdigest() != item['beforeSha256']:
                raise ValueError('Zone file changed since preview: ' + item['zone'])
            changed, serial = prepare_content(original, request['marker'])
            if serial != item['serial']:
                raise ValueError('Prepared serial differs')
            prepared.append((item, path, original, changed))
        backups = []
        # Back up all selected files before writing any. Original permissions/ownership survive writes.
        for item, path, original, _ in prepared:
            backup = path.with_name(path.name + '.before-' + backup_tag)
            fd = os.open(backup, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, 'w') as stream:
                stream.write(original)
            backups.append(str(backup))
        for _, path, _, changed in prepared:
            path.write_text(changed)
        for item, _, _, _ in prepared:
            checked(['rndc', 'reload', item['zone']])
        return {'backups': backups, 'published': len(prepared)}
    raise ValueError('Unknown helper operation')
